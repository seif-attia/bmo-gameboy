// Animated scrolling cave ceiling (creates deep cavern traversal sensation)
static void draw_scrolling_cave(uint8_t offset)
{
    TFT_SetAddrWindow(0, 24, 159, 38);
    TFT_CS_LOW();
    TFT_DC_HIGH();

    for (uint8_t y = 24; y <= 38; y++)
    {
        for (uint8_t x = 0; x < 160; x++)
        {
            uint8_t world_x = (uint8_t)(x + offset);
            if (world_x >= 160)
                world_x -= 160;

            uint8_t bound = pgm_read_byte(&cave_profile[world_x]);
            uint16_t color;
            if (y < bound)
            {
                uint8_t col = world_x % 4;
                if (col == 0)
                    color = 0x0000;
                else if (col == 1)
                    color = 0x02E0;
                else
                    color = (y % 4 == 0) ? 0x02E0 : 0x0180;
            }
            else if (y == bound)
            {
                color = 0x07E0; // Phosphor green contour along stalactites
            }
            else
            {
                color = 0x0000; // Open air below stalactites
            }
            TFT_spiWrite16(color);
        }
    }
    TFT_CS_HIGH();
}

static void draw_ground(uint8_t ground_offset, uint8_t old_ground_offset)
{
    // Animated scrolling floor markers (below GROUND_Y)
    for (uint8_t i = 0; i < 160; i += 20)
    {
        uint8_t old_x = (uint8_t)(i + old_ground_offset) % 160;
        uint8_t new_x = (uint8_t)(i + ground_offset) % 160;

        TFT_DrawPixel(old_x, 118, 0x0000);
        TFT_DrawPixel(old_x + 1, 118, 0x0000);
        TFT_DrawPixel(old_x, 122, 0x0000);

        TFT_DrawPixel(new_x, 118, 0x07E0);
        TFT_DrawPixel(new_x + 1, 118, 0x07E0);
        TFT_DrawPixel(new_x, 122, 0x02E0);
    }
}

static void draw_dino(const PlayerDino *dino)
{
    const uint8_t *sprite;
    if (dino->is_jumping)
        sprite = finn_jake_jump;
    else if (dino->anim_frame)
        sprite = finn_jake_run2;
    else
        sprite = finn_jake_run1;

    if (dino->x >= TFT_WIDTH || dino->y >= TFT_HEIGHT ||
        (dino->x + DINO_W) <= 0 || (dino->y + DINO_H) <= 0)
        return;

    TFT_SetAddrWindow((uint8_t)dino->x, (uint8_t)dino->y,
                      (uint8_t)(dino->x + DINO_W - 1), (uint8_t)(dino->y + DINO_H - 1));

    TFT_CS_LOW();
    TFT_DC_HIGH();

    uint16_t total_bytes = ((uint16_t)DINO_W * DINO_H) / 2;
    for (uint16_t i = 0; i < total_bytes; i++)
    {
        uint8_t b = pgm_read_byte(&sprite[i]);
        uint16_t c1 = pgm_read_word(&dino_palette[b >> 4]);
        uint16_t c2 = pgm_read_word(&dino_palette[b & 0x0F]);
        TFT_spiWrite16(c1);
        TFT_spiWrite16(c2);
    }
    TFT_CS_HIGH();
}

static void spawn_obstacle(Obstacle *obs, bool first_spawn)
{
    uint8_t type = rand() % 3;
    if (type == 0)
    {
        obs->w = 26;
        obs->h = 14;
        obs->bitmap = sleepy_sam_bitmap;
    }
    else if (type == 1)
    {
        obs->w = 16;
        obs->h = 16;
        obs->bitmap = bouncing_colin_bitmap;
    }
    else
    {
        obs->w = 12;
        obs->h = 14;
        obs->bitmap = cave_spikes_bitmap;
    }

    if (first_spawn)
    {
        // First obstacle has plenty of lead-in runway
        obs->x = DINO_SCREEN_WIDTH + 80;
    }
    else
    {
        obs->x = DINO_SCREEN_WIDTH + 35 + (rand() % 50);
    }

    obs->y = GROUND_Y - obs->h;
    obs->old_x = obs->x;
    obs->old_y = obs->y;
    obs->active = true;
}

void play_dino(void)
{
    PlayerDino dino;
    Obstacle obstacle;
    uint16_t score = 0;
    uint16_t old_score = 0xFFFF;
    uint8_t scroll_speed = 4;
    uint8_t run_anim_timer = 0;
    uint8_t old_anim_frame = 0;
    bool old_is_jumping = false;
    uint8_t cave_scroll_offset = 0;
    uint8_t ground_scroll_offset = 0;
    uint8_t old_ground_offset = 0;
    uint8_t cave_scroll_tick = 0;
    GameState current_state = GAME_STATE_START;
    GameState rendered_state = (GameState)0xFF;

    TFT_FillRect(0, 0, DINO_SCREEN_WIDTH, DINO_SCREEN_HEIGHT, 0x0000);

    while (current_state != GAME_STATE_EXIT)
    {
        update_music();

        if (get_key(BACK))
        {
            current_state = GAME_STATE_EXIT;
            break;
        }

        switch (current_state)
        {
        case GAME_STATE_START:
        case GAME_STATE_GAME_OVER:
            if (get_key(START))
            {
                // Reset player position and physics
                dino.x = DINO_X_POS;
                dino.y = GROUND_Y - DINO_H;
                dino.old_x = dino.x;
                dino.old_y = dino.y;
                dino.vy = 0;
                dino.is_jumping = false;
                dino.anim_frame = 0;
                old_anim_frame = 0;
                old_is_jumping = false;
                run_anim_timer = 0;

                // Spawn first obstacle with comfortable preparation distance
                spawn_obstacle(&obstacle, true);

                // Reset score and speed
                score = 0;
                old_score = 0xFFFF;
                scroll_speed = 4;
                cave_scroll_offset = 0;
                ground_scroll_offset = 0;
                old_ground_offset = 0;
                cave_scroll_tick = 0;

                // Clear play area and draw initial scene
                TFT_FillRect(0, 0, DINO_SCREEN_WIDTH, DINO_SCREEN_HEIGHT, 0x0000);
                draw_hud(score, high_score);
                draw_scrolling_cave(cave_scroll_offset);
                TFT_DrawHLine_Fast(0, GROUND_Y, DINO_SCREEN_WIDTH, 0x07E0);
                draw_ground(ground_scroll_offset, old_ground_offset);

                current_state = GAME_STATE_RUNNING;
                rendered_state = GAME_STATE_RUNNING;
            }
            break;

        case GAME_STATE_RUNNING:
            if (get_key(UP) && !dino.is_jumping)
            {
                dino.vy = JUMP_IMPULSE;
                dino.is_jumping = true;
            }
            break;

        default:
            break;
        }

        // UPDATE PHYSICS & COLLISION
        if (current_state == GAME_STATE_RUNNING)
        {
            dino.old_y = dino.y;
            obstacle.old_x = obstacle.x;
            old_anim_frame = dino.anim_frame;
            old_is_jumping = dino.is_jumping;
            old_ground_offset = ground_scroll_offset;

            // Player jump physics (smooth and responsive)
            dino.y += dino.vy;
            dino.vy += GRAVITY;

            if (dino.y >= GROUND_Y - DINO_H)
            {
                dino.y = GROUND_Y - DINO_H;
                dino.vy = 0;
                dino.is_jumping = false;
            }

            // Running leg animation toggle
            if (!dino.is_jumping)
            {
                run_anim_timer++;
                if (run_anim_timer >= 3)
                {
                    dino.anim_frame = !dino.anim_frame;
                    run_anim_timer = 0;
                }
            }

            // Ground & cave parallax traversal scroll
            ground_scroll_offset = (uint8_t)(ground_scroll_offset + scroll_speed) % 160;

            cave_scroll_tick++;
            if (cave_scroll_tick >= 2)
            {
                cave_scroll_offset = (uint8_t)(cave_scroll_offset + 1) % 160;
                cave_scroll_tick = 0;
            }

            // Obstacle movement
            obstacle.x -= scroll_speed;

            // Obstacle respawn & score progression
            if (obstacle.x + obstacle.w < 0)
            {
                spawn_obstacle(&obstacle, false);
                score += 10;

                if (score % 60 == 0 && scroll_speed < 7)
                {
                    scroll_speed++;
                }
            }

            // Forgiving, arcade-accurate hitbox collision check
            int16_t dino_bx = dino.x + 5;
            int16_t dino_bw = DINO_W - 10;
            int16_t dino_by = dino.y + 4;
            int16_t dino_bh = DINO_H - 4;

            int16_t obs_bx = obstacle.x + 3;
            int16_t obs_bw = obstacle.w - 6;
            int16_t obs_by = obstacle.y + 2;
            int16_t obs_bh = obstacle.h - 2;

            if (dino_bx < obs_bx + obs_bw &&
                dino_bx + dino_bw > obs_bx &&
                dino_by < obs_by + obs_bh &&
                dino_by + dino_bh > obs_by)
            {
                current_state = GAME_STATE_GAME_OVER;
            }
        }

        // RENDER FRAME
        if (current_state == GAME_STATE_START)
        {
            if (rendered_state != GAME_STATE_START)
            {
                TFT_FillRect(0, 0, DINO_SCREEN_WIDTH, DINO_SCREEN_HEIGHT, 0x0000);
                draw_hud(0, high_score);
                draw_scrolling_cave(0);
                TFT_DrawHLine_Fast(0, GROUND_Y, DINO_SCREEN_WIDTH, 0x07E0);
                draw_ground(0, 0);

                // Retro Green Start Modal Box
                TFT_FillRect(14, 50, 132, 46, 0x0000);
                TFT_DrawHLine_Fast(14, 50, 132, 0x07E0);
                TFT_DrawHLine_Fast(14, 95, 132, 0x07E0);
                TFT_DrawVLine_Fast(14, 50, 46, 0x07E0);
                TFT_DrawVLine_Fast(145, 50, 46, 0x07E0);

                TFT_DrawString(20, 56, "GAURDIANS OF SUNSHINE", 0x07E0, 0x0000, 1);
                TFT_DrawString(38, 70, "START: Play", 0x07E0, 0x0000, 1);
                TFT_DrawString(40, 82, "BACK: Exit", 0x03E0, 0x0000, 1);

                // Preview player on floor
                PlayerDino preview;
                preview.x = DINO_X_POS;
                preview.y = GROUND_Y - DINO_H;
                preview.is_jumping = false;
                preview.anim_frame = 0;
                draw_dino(&preview);

                rendered_state = GAME_STATE_START;
            }
        }
        else if (current_state == GAME_STATE_GAME_OVER)
        {
            if (rendered_state != GAME_STATE_GAME_OVER)
            {
                // Retro Green Game Over Modal Box
                TFT_FillRect(20, 50, 120, 46, 0x0000);
                TFT_DrawHLine_Fast(20, 50, 120, 0x07E0);
                TFT_DrawHLine_Fast(20, 95, 120, 0x07E0);
                TFT_DrawVLine_Fast(20, 50, 46, 0x07E0);
                TFT_DrawVLine_Fast(139, 50, 46, 0x07E0);

                TFT_DrawString(52, 56, "GAME OVER", 0x07E0, 0x0000, 1);
                TFT_DrawString(32, 70, "START: Restart", 0x07E0, 0x0000, 1);
                TFT_DrawString(44, 82, "BACK: Exit", 0x03E0, 0x0000, 1);

                rendered_state = GAME_STATE_GAME_OVER;
            }
        }
        else if (current_state == GAME_STATE_RUNNING)
        {
            // Update scrolling cave ceiling (creates continuous traversal animation)
            if (cave_scroll_tick == 0)
            {
                draw_scrolling_cave(cave_scroll_offset);
            }

            // Clear old player bounds if position, frame, or jump state changed
            if (dino.old_y != dino.y || dino.anim_frame != old_anim_frame || dino.is_jumping != old_is_jumping)
            {
                TFT_FillRect(dino.old_x, dino.old_y, DINO_W, DINO_H, 0x0000);
            }

            // Clear old obstacle bounds
            if (obstacle.old_x != obstacle.x)
            {
                TFT_FillRect(obstacle.old_x, obstacle.y, obstacle.w, obstacle.h, 0x0000);
            }

            // Update scrolling ground marks below floor line
            draw_ground(ground_scroll_offset, old_ground_offset);

            // Ensure ground line remains intact
            TFT_DrawHLine_Fast(0, GROUND_Y, DINO_SCREEN_WIDTH, 0x07E0);

            // Render player (Finn riding Jake-Dino)
            draw_dino(&dino);

            // Render obstacle (Sleepy Sam, Colin, or Spikes)
            TFT_DrawBitmap1Bit_Scaled_Clipped(
                obstacle.x, obstacle.y, obstacle.bitmap,
                obstacle.w, obstacle.h, 0x07E0, 0x0000, 1);

            // Update Score HUD
            if (score != old_score)
            {
                char score_str[7];
                utoa(score, score_str, 10);

                TFT_FillRect(52, 14, 36, 8, 0x0000);
                TFT_DrawString(52, 14, score_str, 0x07E0, 0x0000, 1);

                if (score > high_score)
                {
                    high_score = score;
                }
                utoa(high_score, score_str, 10);
                TFT_FillRect(120, 14, 36, 8, 0x0000);
                TFT_DrawString(120, 14, score_str, 0x07E0, 0x0000, 1);

                old_score = score;
            }
        }

        _delay_ms(30);
    }
    stop_song();
}
